def ensure_popular_device_models() -> None:
    for (
        brand_name,
        type_name,
        model_name,
        model_number,
        release_year,
    ) in POPULAR_DEVICE_MODELS:
        brand, _ = DeviceBrand.objects.get_or_create(name=brand_name)
        device_type, _ = DeviceType.objects.get_or_create(
            name=type_name,
            defaults={"icon": _device_type_icon(type_name)},
        )
        model = DeviceModel.objects.filter(brand=brand, name=model_name).first()
        if model:
            updates = []
            if not model.model_number and model_number:
                model.model_number = model_number
                updates.append("model_number")
            if not model.release_year and release_year:
                model.release_year = release_year
                updates.append("release_year")
            if updates:
                model.save(update_fields=updates)
            continue

        DeviceModel.objects.create(
            brand=brand,
            device_type=device_type,
            name=model_name,
            model_number=model_number,
            release_year=release_year,
        )


def popular_device_model_ordering():
    return Case(
        *[
            When(brand__name=brand_name, name=model_name, then=Value(index))
            for index, (brand_name, _, model_name, _, _) in enumerate(
                POPULAR_DEVICE_MODELS
            )
        ],
        default=Value(len(POPULAR_DEVICE_MODELS) + 1000),
        output_field=IntegerField(),
    )


def _device_type_icon(type_name: str) -> str:
    icons = {
        "Смартфон": "smartphone",
        "Планшет": "tablet_mac",
        "Ноутбук": "laptop_mac",
    }
    return icons.get(type_name, "devices")
